import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] })
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
page.on('pageerror', (e) => console.log('PAGEERROR', e.message))
await page.goto('http://localhost:4174/')
await page.getByTestId('load-demo').click()
await page.getByRole('checkbox', { name: /Place station elements/ }).uncheck()
for (const t of ['Neon Parking Lot', 'Boombox Heart', 'Raccoon Radio', 'Sunday Sticker']) await page.getByRole('button', { name: new RegExp(`^Add ${t} to the show$`) }).click()
await page.waitForTimeout(500)
const handles = page.locator('[aria-label^="Move "][aria-label$="arrow keys."]')
const rows = page.locator('[data-testid="rundown"] li')
console.log('rows', await rows.count())
const a = await handles.first().boundingBox(); const r = await rows.nth(3).boundingBox()
console.log(a, r)
const live = () => page.evaluate(() => [...document.querySelectorAll('[aria-live]')].map(e => e.textContent).filter(t => /Draggable/.test(t)))
await page.mouse.move(a.x + a.width/2, a.y + a.height/2); await page.mouse.down()
await page.mouse.move(a.x + a.width/2 + 8, a.y + a.height/2 + 8, { steps: 3 })
await page.mouse.move(r.x + r.width/2, r.y + r.height/2 + 30, { steps: 18 })
await page.waitForTimeout(150)
console.log(await live())
await page.mouse.up(); await page.waitForTimeout(400)
console.log(await live())
console.log(await handles.evaluateAll(e => e.map(x => x.getAttribute('aria-label').split('.')[0])))
await page.screenshot({ path: '/tmp/claude-0/-home-claude/f98ac2b7-c3c4-5e91-9992-4e460ece75c1/scratchpad/shots/drag-debug.png' })
await browser.close()
